// Release builds on Windows are GUI-subsystem apps (no console window).
#![cfg_attr(all(windows, not(debug_assertions)), windows_subsystem = "windows")]

use std::sync::OnceLock;

use clap::Parser;
use iced::{Settings, Task};
use tokenburn_core::{Currency, Query};
use tokenburn_gui::state::AUTO_REFRESH;
use tokenburn_gui::{Args, Message, TokenBurn};

/// Initial query, theme and currency from the command line (read once by `boot`).
static INITIAL: OnceLock<(Query, Option<usize>, Option<Currency>)> = OnceLock::new();

fn main() -> iced::Result {
    // Handles --help / --version before any window is created.
    let args = Args::parse();
    if args.list_themes {
        for name in tokenburn_core::THEME_NAMES {
            println!("{name}");
        }
        return Ok(());
    }
    if args.list_currencies {
        for c in tokenburn_core::CURRENCIES {
            println!("{:<4}{}", c.code, c.name);
        }
        return Ok(());
    }
    let _ = INITIAL.set((args.query(), args.theme, args.currency));

    tracing_subscriber::fmt::init();

    iced::application(boot, TokenBurn::update, TokenBurn::view)
        .title("TokenBurn — AI token usage")
        .theme(|state: &TokenBurn| state.iced_theme())
        .subscription(subscription)
        .settings(Settings {
            default_text_size: iced::Pixels(14.0),
            ..Default::default()
        })
        .window(window_settings())
        .centered()
        .run()
}

/// Boot function — initial state plus the first load.
fn boot() -> (TokenBurn, Task<Message>) {
    let (query, theme, currency) = INITIAL.get().copied().unwrap_or_default();
    let mut state = TokenBurn::with_query(query);
    state.persist = true;
    match theme {
        Some(i) => state.set_theme(i), // an explicit --theme is remembered
        None => state.theme_index = tokenburn_core::settings::theme_index(),
    }
    // The user's own exchange rates, then the currency: an explicit --currency is
    // remembered like --theme, otherwise the saved one is used.
    state.rates = tokenburn_core::settings::load().rates;
    match currency {
        Some(c) => state.set_currency(tokenburn_core::features::currency::index_of(c.code)),
        None => state.currency = tokenburn_core::settings::currency(),
    }
    let task = state.reload();
    (state, task)
}

fn subscription(state: &TokenBurn) -> iced::Subscription<Message> {
    // Always on: the numbers track live sessions.
    let auto_refresh = iced::Subscription::run(auto_refresh_stream);
    // Spinner animation only while a load is in flight.
    let animation = if state.is_loading {
        iced::Subscription::run(animation_tick_stream)
    } else {
        iced::Subscription::none()
    };
    // Display frames only while a chart animation is running, so an idle window
    // costs nothing.
    let frames = if state.is_animating() {
        iced::window::frames().map(Message::Frame)
    } else {
        iced::Subscription::none()
    };
    iced::Subscription::batch([auto_refresh, animation, frames])
}

/// Emits `AutoRefresh` every [`AUTO_REFRESH`]. Blocking sleep is fine: Iced runs
/// each subscription on its own worker thread.
fn auto_refresh_stream() -> impl futures::Stream<Item = Message> {
    futures::stream::unfold((), |()| async {
        std::thread::sleep(AUTO_REFRESH);
        Some((Message::AutoRefresh, ()))
    })
}

/// Emits `AnimationTick` at ~10 fps.
fn animation_tick_stream() -> impl futures::Stream<Item = Message> {
    futures::stream::unfold((), |()| async {
        std::thread::sleep(std::time::Duration::from_millis(100));
        Some((Message::AnimationTick, ()))
    })
}

/// 64×64 raw RGBA window icon (generated by `scripts/gen_icons.py`).
const ICON_RGBA: &[u8] = include_bytes!("../assets/icon-64.rgba");

/// Window settings shared by every platform.
///
/// On Linux the `application_id` becomes the Wayland `app_id` and the X11
/// `WM_CLASS`. It must match the basename of the installed `.desktop` file
/// (`tokenburn-gui.desktop`) so compositors/panels show the right icon and
/// group windows correctly on both Wayland and X11.
fn window_settings() -> iced::window::Settings {
    iced::window::Settings {
        size: iced::Size::new(1200.0, 760.0),
        min_size: Some(iced::Size::new(720.0, 480.0)),
        icon: iced::window::icon::from_rgba(ICON_RGBA.to_vec(), 64, 64).ok(),
        #[cfg(target_os = "linux")]
        platform_specific: iced::window::settings::PlatformSpecific {
            application_id: "tokenburn-gui".to_string(),
            ..Default::default()
        },
        ..Default::default()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn icon_blob_is_64x64_rgba() {
        assert_eq!(ICON_RGBA.len(), 64 * 64 * 4);
        assert!(iced::window::icon::from_rgba(ICON_RGBA.to_vec(), 64, 64).is_ok());
    }

    #[test]
    fn window_has_icon_and_minimum_size() {
        let s = window_settings();
        assert!(s.icon.is_some());
        assert!(s.min_size.is_some());
    }
}
